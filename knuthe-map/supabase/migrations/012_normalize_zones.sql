-- ── zones 테이블 ─────────────────────────────────────────────────────────────
update public.zones
  set name = replace(name, '구역', '')
  where name like '%구역';

-- ── buildings.zone ────────────────────────────────────────────────────────────
update public.buildings
  set zone = replace(zone, '구역', '')
  where zone like '%구역';

-- ── map_layers.zone ───────────────────────────────────────────────────────────
update public.map_layers
  set zone = replace(zone, '구역', '')
  where zone like '%구역';

